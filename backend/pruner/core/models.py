# --------------------------------------------------------------------------- API requests


class StartRunRequest(BaseModel):
    question: str
    spec: str = ""  # the research specs; stored as the run's first instruction (kind "spec")
    mode: RunMode = "pruned"
    # Person names become vault file names, so they follow PERSON_PATTERN (no "../", no "/").
    primary_person: str = Field(pattern=PERSON_PATTERN)
    people: list[str] | None = None  # defaults to [primary_person]
    # Whose vaults the pre- and post-scorers search, e.g. just you, or you plus a teammate.
    # Defaults to [primary_person]; an empty list scores with no vault at all.
    vault_people: list[str] | None = None
    # The person's active directives (their texts), sent along with the spec. They are appended
    # to the prompts as-is.
    directives: list[str] = Field(default_factory=list)
    # Files or folders on this machine the run works on. A folder means any file under it may be
    # changed; listed files mean only those. They are edited in place (a backup is kept).
    paths: list[str] = Field(default_factory=list, max_length=50)
    manual: bool = False  # start in manual mode (it can be switched any time later)

    @field_validator("people", "vault_people")
    @classmethod
    def _person_names(cls, names: list[str] | None) -> list[str] | None:
        for name in names or []:
            if not re.fullmatch(PERSON_PATTERN, name):
                raise ValueError(f"{name!r} is not a valid person name (lowercase letters, "
                                 f"digits, _ and -)")
        return names

    @field_validator("paths")
    @classmethod
    def _existing_absolute_paths(cls, paths: list[str]) -> list[str]:
        out = []
        for p in paths:
            if not os.path.isabs(p):
                raise ValueError(f"{p!r} is not an absolute path")
            real = os.path.realpath(p)
            if not os.path.exists(real):
                raise ValueError(f"{p!r} does not exist")
            out.append(real)
        return list(dict.fromkeys(out))


class InstructionRequest(BaseModel):
    """Further instructions typed mid-run; appended to the spec and sent to the agent."""

    text: str = Field(min_length=1)
    # The current list of active directives, replacing the run's previous list. Omit to keep it.
    directives: list[str] | None = None


class ManualRequest(BaseModel):
    """Body of POST /runs/{id}/manual: turn manual mode on or off."""

    manual: bool


class InstructionToggle(BaseModel):
    """Body of PATCH /runs/{id}/instructions/{instruction_id}: turn a steering chip on or off."""

    active: bool


class IngestRequest(BaseModel):
    person: str = Field(pattern=PERSON_PATTERN)
    kind: VaultKind = "note"
    text: str = Field(min_length=1)
    title: str | None = None  # optional override; otherwise the ingest LLM writes one
    # Topic tags, chosen by the person (the ingest LLM no longer writes them). Normalized to
    # lowercase-hyphenated, deduplicated and capped at 5 when stored.
    tags: list[str] = Field(default_factory=list)

    @field_validator("kind")
    @classmethod
    def _not_a_directive(cls, kind: str) -> str:
        if kind == "directive":
            raise ValueError("directives are not vault items; use POST /api/vault/directives")
        return kind


class MoveItemRequest(Position):
    """The move tool: where the card now sits. Body of PATCH /vault/items/{id}/position."""


class ItemPosition(Position):
    id: str


class MoveItemsRequest(BaseModel):
    """Several moves at once, e.g. after dragging a group of cards."""

    positions: list[ItemPosition] = Field(min_length=1)


class RegenerateLayoutRequest(BaseModel):
    """Recompute every card's automatic position. Cards a person moved keep their spot unless
    reset_moved is true, which also forgets the manual moves."""

    reset_moved: bool = False


class CreateVaultRequest(BaseModel):
    person: str = Field(pattern=PERSON_PATTERN)


class VaultSummary(BaseModel):
    person: str
    item_count: int


class PromptInfo(BaseModel):
    name: str
    text: str
    placeholders: list[str]  # the {{names}} the backend fills in


class StopResult(BaseModel):
    run_id: str
    cancelled_calls: int  # LLM calls that were in flight and are now cancelled


